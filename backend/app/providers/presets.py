"""Curated provider presets with setup guides (spec req 2).

Each preset is a ready-to-use configuration that maps onto a registered provider
implementation. Most free LLM services are OpenAI-compatible, so they reuse the
``openai`` implementation with a different endpoint/model. This lets the UI show
a gallery of providers with step-by-step guides instead of a blank form.

Model names and free-tier terms change often; ``suggested_models`` are hints and
the guide tells the user to pick a current model from the provider's console.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field

from app.core.enums import Capability


@dataclass
class ProviderPreset:
    id: str
    capability: Capability
    provider: str  # registered implementation key to use
    display_name: str
    description: str
    free: bool
    free_details: str
    requires_api_key: bool
    default_endpoint: str
    default_model: str
    suggested_models: list[str]
    signup_url: str
    docs_url: str
    api_key_label: str
    setup_steps: list[str] = field(default_factory=list)
    recommended: bool = False

    def to_dict(self) -> dict:
        data = asdict(self)
        data["capability"] = self.capability.value
        return data


def _get_key_steps(where: str, url_label: str) -> list[str]:
    return [
        f"Open {where} and sign in (or create a free account).",
        f"Go to {url_label} and create a new API key.",
        "Copy the key.",
        "Paste it into the API key field here and click Add provider.",
        "Click Test to confirm it works.",
    ]


